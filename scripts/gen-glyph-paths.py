#!/usr/bin/env python3
"""Regenerate src/components/glyphs/paths.ts from desktop codenotch's
Sources/Providers/GlyphOutline.swift.

    python3 scripts/gen-glyph-paths.py /path/to/codenotch/Sources/Providers/GlyphOutline.swift

Each outline is a list of polygons in a unit box; they become one SVG path in a
0..100 viewBox, filled even-odd by ProviderGlyph.
"""
import re
import sys
from pathlib import Path

HEADER = '''/**
 * Provider marks, ported verbatim from desktop codenotch's GlyphOutline.swift
 * (traced from its design frame and normalised into a unit box). Scaled to a
 * 0..100 viewBox and filled even-odd, so the OpenAI knot's counters stay open.
 * Generated by scripts/gen-glyph-paths.py — do not edit by hand.
 */
export const glyphPaths = {
'''

POINT = re.compile(r"CGPoint\(x:\s*([-\d.]+),\s*y:\s*([-\d.]+)\)")
BAR = re.compile(r"bar\(x:\s*([-\d.]+)\)")


def bar(x):
    # Mirrors GlyphOutline.bar(x:): one upright tally stroke.
    width, top, bottom = 2.6 / 24, 3.5 / 24, 20.5 / 24
    return [(x, top), (x + width, top), (x + width, bottom), (x, bottom)]


def fmt(v):
    text = f"{v * 100:.2f}".rstrip("0").rstrip(".")
    return "0" if text in ("-0", "") else text


def polygons(body):
    out = []
    depth, start = 0, None
    for i, ch in enumerate(body):
        if ch == "[":
            depth += 1
            if depth == 1:
                start = i
        elif ch == "]":
            if depth == 1 and start is not None:
                pts = [(float(x), float(y)) for x, y in POINT.findall(body[start:i])]
                if pts:
                    out.append(pts)
            depth -= 1
    out.extend(bar(float(x)) for x in BAR.findall(body))
    return out


def main(src):
    text = Path(src).read_text()
    blocks = re.finditer(r"static let (\w+): \[\[CGPoint\]\] = \[(.*?)\n    \]\n", text, re.S)
    lines = []
    for match in blocks:
        name, body = match.group(1), match.group(2)
        polys = polygons(body)
        if not polys:
            continue
        d = "".join(
            "M" + "L".join(f"{fmt(x)} {fmt(y)}" for x, y in poly) + "Z" for poly in polys
        )
        lines.append(f'  {name}: "{d}",\n')
    out = Path(__file__).resolve().parent.parent / "src/components/glyphs/paths.ts"
    out.write_text(HEADER + "".join(lines) + "} as const;\n")
    print(f"wrote {len(lines)} glyphs to {out}")


if __name__ == "__main__":
    main(sys.argv[1])
